//! Where one character ends and the next begins, and how many columns it
//! takes. A character here is what a reader calls one: a grapheme cluster,
//! cut exactly as Unicode's UAX #29 says (`Joiner`). Its width is one rule
//! (`width`): the columns of its characters added up, two at most. A
//! character adds two if it is East Asian wide or fullwidth or has emoji
//! presentation (but half a flag adds one), none if it is a mark, a joiner or the vowel or final
//! consonant of a Hangul syllable, one otherwise, "ambiguous" ones too; and
//! U+FE0F after an emoji makes the cluster two. What cannot start a
//! character on a screen (a control, a mark or a joiner with nothing before
//! it) has no width.
//!
//! The table is Unicode's, written out by `tools/unicode.py`: no data is read
//! when fux is built or run.

// What a table entry says of a character: its kind for cutting (the low four
// bits, in UAX #29's names), its part in an Indic conjunct, and three flags.
const KIND: u16 = 0xf;
const CR: u16 = 1;
const LF: u16 = 2;
const CONTROL: u16 = 3;
const EXTEND: u16 = 4;
const JOINER: u16 = 5;
const REGIONAL: u16 = 6;
const PREPEND: u16 = 7;
const SPACING: u16 = 8;
const L: u16 = 9;
const V: u16 = 10;
const T: u16 = 11;
const LV: u16 = 12;
const LVT: u16 = 13;
// The two bits of a conjunct's parts; both set is a mark inside one.
const CONJUNCT: u16 = 0x30;
const CONSONANT: u16 = 0x10;
const LINKER: u16 = 0x20;
const PICTURE: u16 = 0x40;
const WIDE: u16 = 0x80;
const EMOJI: u16 = 0x100;

fn class(c: char) -> u16 {
    match c as u32 {
        0x0d => CR,
        0x0a => LF,
        0x00..0x20 | 0x7f => CONTROL,
        // The table starts after ASCII, whose only emoji are the keycaps' bases.
        0x23 | 0x2a | 0x30..0x3a => EMOJI,
        0x20..0x7f => 0,
        // Hangul syllables: every twenty-eighth has no final consonant.
        c @ 0xac00..0xd7a4 => WIDE | if (c - 0xac00) % 28 == 0 { LV } else { LVT },
        c => RUNS.get(RUNS.partition_point(|&(start, _)| start <= c).wrapping_sub(1)).map_or(0, |&(_, class)| class),
    }
}

/// What must be known of the characters so far to tell whether the next one
/// goes on with the same cluster.
#[derive(Clone, Copy, Default, PartialEq, Eq, Debug)]
pub struct Joiner {
    /// The class of the character before, and that there was one.
    before: Option<u16>,
    /// An emoji and marks came before (and then a joiner).
    picture: bool,
    picture_joined: bool,
    /// An odd number of regional indicators came before: the next one makes a flag.
    regional: bool,
    /// A consonant of a conjunct came before (and then a linker).
    consonant: bool,
    linked: bool,
}

impl Joiner {
    /// Whether `c` belongs to the cluster of the characters given before it.
    pub fn joins(&mut self, c: char) -> bool {
        let class = class(c);
        let (kind, conjunct) = (class & KIND, class & CONJUNCT);
        let joins = self.before.is_some_and(|before| match (before & KIND, kind) {
            (CR, LF) => true,
            (CR | LF | CONTROL, _) | (_, CR | LF | CONTROL) => false,
            (L, L | V | LV | LVT) | (LV | V, V | T) | (LVT | T, T) => true,
            (_, EXTEND | JOINER | SPACING) | (PREPEND, _) => true,
            _ => {
                (self.linked && conjunct == CONSONANT)
                    || (self.picture_joined && class & PICTURE != 0)
                    || (self.regional && kind == REGIONAL)
            }
        });
        self.picture_joined = self.picture && kind == JOINER;
        self.picture = class & PICTURE != 0 || (self.picture && kind == EXTEND);
        self.regional = kind == REGIONAL && !self.regional;
        self.linked = self.consonant && (conjunct == LINKER || (self.linked && conjunct == CONJUNCT));
        self.consonant = conjunct == CONSONANT || (self.consonant && conjunct != 0);
        self.before = Some(class);
        joins
    }
}

/// The columns one character of a cluster adds to it.
fn columns(c: char) -> usize {
    match class(c) {
        class if class & WIDE != 0 => 2,
        // Marks and joiners take no room, nor do the vowel and the final consonant of a Hangul syllable.
        class if matches!(class & KIND, CR | LF | CONTROL | EXTEND | JOINER | V | T) => 0,
        _ => 1,
    }
}

/// The columns of a cluster, its first character and the rest of it: those
/// of its characters added up, two at most, and two if U+FE0F asks an emoji
/// for its picture. None if it starts with what cannot start one on a screen.
pub fn width(first: char, rest: &[char]) -> usize {
    let class = class(first);
    if matches!(class & KIND, CR | LF | CONTROL | EXTEND | JOINER) {
        0
    } else if class & EMOJI != 0 && rest.contains(&'\u{fe0f}') {
        2
    } else {
        (columns(first) + rest.iter().map(|&c| columns(c)).sum::<usize>()).clamp(1, 2)
    }
}

/// The most columns the same characters take in a terminal that does not
/// join what is joined here: all of them added up, half a flag as the two
/// that some give it.
pub fn spread(first: char, rest: &[char]) -> usize {
    let most = |c: char| if class(c) & KIND == REGIONAL { 2 } else { columns(c) };
    most(first) + rest.iter().map(|&c| most(c)).sum::<usize>()
}

