fn within(table: &[(u32, u32)], c: u32) -> bool {
    table
        .binary_search_by(|&(low, high)| {
            if c < low {
                std::cmp::Ordering::Greater
            } else if c > high {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

pub fn width(c: char) -> usize {
    let c = c as u32;
    if c < 0x300 {
        1
    } else if within(ZERO, c) {
        0
    } else if within(WIDE, c) {
        2
    } else {
        1
    }
}
